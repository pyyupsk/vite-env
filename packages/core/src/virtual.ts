import type { AnyEnvDefinition } from "./types";

export type ServerRuntimeMode = "build-time" | "process-env";

function getAllKeys(def: AnyEnvDefinition): string[] {
  const serverKeys = Object.keys(def.server ?? {});
  const clientKeys = Object.keys(def.client ?? {});
  return [...new Set([...serverKeys, ...clientKeys])];
}

function buildInlinedModule(data: Record<string, unknown>): { code: string; moduleType: "js" } {
  return {
    moduleType: "js",
    code: `// Auto-generated by @vite-env/core — do not edit
export const env = Object.freeze(${JSON.stringify(data, null, 2)});
export default env;`,
  };
}

/**
 * Emits `process.env["KEY"]` references instead of inlined literals, so the actual
 * values are read at runtime from the container/host environment rather than baked
 * into the built code. Bracket notation is used for every key (not just keys that
 * aren't valid identifiers) to keep the output uniform.
 *
 * Values are NOT coerced/defaulted here — build-time validation still runs (schema
 * checking, type generation), but a runtime process.env read is always a raw string
 * (or undefined if unset). Reproducing build-time coercion/defaults at runtime would
 * silently diverge from what was validated, so this mode intentionally leaves that
 * to the runtime environment.
 */
function buildProcessEnvModule(keys: string[]): { code: string; moduleType: "js" } {
  const entries = keys
    .map((key) => `  ${JSON.stringify(key)}: process.env[${JSON.stringify(key)}],`)
    .join("\n");
  return {
    moduleType: "js",
    code: `// Auto-generated by @vite-env/core — do not edit
export const env = Object.freeze({
${entries}
});
export default env;`,
  };
}

export function buildClientModule(
  def: AnyEnvDefinition,
  data: Record<string, unknown>,
): { code: string; moduleType: "js" } {
  const clientKeys = new Set(Object.keys(def.client ?? {}));
  const clientData = Object.fromEntries(Object.entries(data).filter(([k]) => clientKeys.has(k)));
  return buildInlinedModule(clientData);
}

export function buildServerModule(
  def: AnyEnvDefinition,
  data: Record<string, unknown>,
  serverRuntime: ServerRuntimeMode = "build-time",
): { code: string; moduleType: "js" } {
  if (serverRuntime === "process-env") {
    const keys = getAllKeys(def);
    const dataKeys = Object.keys(data).filter((k) => keys.includes(k));
    return buildProcessEnvModule(dataKeys);
  }
  return buildInlinedModule(data);
}
